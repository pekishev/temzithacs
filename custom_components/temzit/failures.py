NO_FAILURE = "Нет аварии"


def decode_failures(code: int) -> dict[str, object]:
    """Decode the Failures word into codes and messages."""
    value = int(code) & 0xFFFFFFFF
    if value == 0:
        return {
            "codes": [],
            "messages": [],
            "description": NO_FAILURE,
        }

    codes: list[str] = []
    messages: list[str] = []
    for bit in range(32):
        if (value >> bit) & 1 == 0:
            continue
        if bit < len(FAILURES):
            short, message = FAILURES[bit]
        else:
            short = f"bit{bit}"
            message = f"Неизвестная авария. Код: {value} (сдвиг {bit})"
        codes.append(short)
        messages.append(message)

    return {
        "codes": codes,
        "messages": messages,
        "description": "; ".join(messages),
    }
